// Writes the crafting review drafts to docs/crafting-review/: every reference item's recipe and
// every species' work profile, so the rules in shared/crafting.ts and the exceptions in
// data/crafting-*.json can be checked. Run with `pnpm crafting:report`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import {
  CRAFTING_SKILLS, SKILL_AFFINITIES, TIERS, itemPrice, itemRecipe, speciesOverrides, workProfile,
  type ItemExceptions, type ProfileSkill, type Recipe, type SpeciesExceptions,
} from '../shared/crafting.ts';
import type { Item, PokemonTemplate } from '../shared/types.ts';

const read = <T>(path: string): T => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const items = read<Item[]>('../data/reference/items.json');
const templates = read<PokemonTemplate[]>('../data/reference/pokemon-templates.json');
const itemExceptions = read<ItemExceptions>('../data/crafting-items.json');
const speciesExceptions = read<SpeciesExceptions>('../data/crafting-species.json');

const label = (value: string) => value.toLowerCase().split('_').map(word => word[0].toUpperCase() + word.slice(1)).join(' ');
const types = (list: readonly string[] | null) => list?.map(label).join(' / ') ?? '';
const target = new URL('../docs/crafting-review/', import.meta.url);
mkdirSync(target, { recursive: true });

const unknownItems = Object.keys(itemExceptions).filter(name => !items.some(item => item.name === name));
const unknownSpecies = Object.keys(speciesExceptions).filter(name => !templates.some(t => t.name === name));
if (unknownItems.length || unknownSpecies.length) throw new Error(`Exceptions name unknown entries: ${[...unknownItems, ...unknownSpecies].join(', ')}`);

// Recipes
const recipes = items.map(item => ({ item, recipe: itemRecipe(item, itemExceptions[item.name]) }));
const craftable = recipes.filter(({ recipe }) => recipe.craftable);
const tierNumbers = Object.keys(TIERS).map(Number) as Recipe['tier'][];
const assist = (recipe: Recipe) => recipe.assist ? `${label(recipe.assist.skill)} ${recipe.assist.min}` : '';
const recipeLines = [
  '# Crafting review: recipes',
  '',
  'Generated by `pnpm crafting:report` from `data/reference/items.json`, the rules in `shared/crafting.ts` and the',
  'exceptions in `data/crafting-items.json`. Edit the exceptions (or the rules) and re-run; do not edit this file.',
  'Rows marked ✎ come from an exception.',
  '',
  '## Craftable items per skill and tier',
  '',
  `| Skill | ${tierNumbers.map(tier => `T${tier}`).join(' | ')} | Total |`,
  `|---|${tierNumbers.map(() => '---:').join('|')}|---:|`,
  ...CRAFTING_SKILLS.map(skill => {
    const own = craftable.filter(({ recipe }) => recipe.skill === skill);
    return `| ${label(skill)} | ${tierNumbers.map(tier => own.filter(({ recipe }) => recipe.tier === tier).length).join(' | ')} | ${own.length} |`;
  }),
  `| **All** | ${tierNumbers.map(tier => craftable.filter(({ recipe }) => recipe.tier === tier).length).join(' | ')} | ${craftable.length} |`,
  '',
  `${craftable.filter(({ recipe }) => recipe.catalyst).length} recipes need a catalyst; ${recipes.length - craftable.length} items are not craftable.`,
  '',
  '## Tiers',
  '',
  '| Tier | Min skill | Min city rank | Effort (skill used per item) | Research steps | Min Research | Catalyst strength |',
  '|---|---:|---|---:|---:|---:|---:|',
  ...tierNumbers.map(tier => {
    const t = TIERS[tier];
    return `| ${tier} | ${t.minSkill} | ${label(t.minRank)} | ${t.effort} | ${t.research?.steps ?? '-'} | ${t.research?.minResearch ?? '-'} | ${t.catalystStrength} |`;
  }),
];
for (const skill of CRAFTING_SKILLS) {
  const own = craftable.filter(({ recipe }) => recipe.skill === skill)
    .sort((a, b) => a.recipe.tier - b.recipe.tier || a.item.name.localeCompare(b.item.name));
  recipeLines.push('', `## ${label(skill)} (${own.length})`, '', '| Tier | Item | Pocket / category | Price | Catalyst | Assist |', '|---:|---|---|---:|---|---|');
  for (const { item, recipe } of own) {
    const edited = itemExceptions[item.name] ? ' ✎' : '';
    recipeLines.push(`| ${recipe.tier} | ${item.name}${edited} | ${label(item.pocket)}${item.category ? ` / ${label(item.category)}` : ''} | ${itemPrice(item) ?? ''} | ${types(recipe.catalyst)} | ${assist(recipe)} |`);
  }
}
recipeLines.push('', '## Not craftable', '', '| Item | Reason |', '|---|---|',
  ...recipes.filter(({ recipe }) => !recipe.craftable).map(({ item, recipe }) => `| ${item.name} | ${recipe.note ?? ''} |`));
writeFileSync(new URL('recipes.md', target), recipeLines.join('\n') + '\n');

// Species work profiles
const overrides = speciesOverrides(templates, speciesExceptions);
const profiles = [...templates].sort((a, b) => a.number - b.number || a.name.localeCompare(b.name))
  .map(template => ({ template, profile: workProfile(template, overrides.get(template.name)) }));
const skills = Object.keys(SKILL_AFFINITIES) as ProfileSkill[];
const craftingCount = (profile: ReturnType<typeof workProfile>) => CRAFTING_SKILLS.filter(skill => profile[skill]).length;
const speciesLines = [
  '# Crafting review: species work profiles',
  '',
  'Generated by `pnpm crafting:report` from `data/reference/pokemon-templates.json`, the rules in `shared/crafting.ts`',
  'and the exceptions in `data/crafting-species.json`. Edit the exceptions (or the rules) and re-run; do not edit this file.',
  'A resident adds its full bonus to a "full" skill and half (at least 1) to a "half" skill; it cannot work any other',
  'skill except Catalyst. Species marked ✎ have an exception.',
  '',
  '## How the profile starts',
  '',
  '| Skill | Full-bonus types | Half-bonus types | Key attribute |',
  '|---|---|---|---|',
  ...skills.map(skill => `| ${label(skill)} | ${types(SKILL_AFFINITIES[skill].full)} | ${types(SKILL_AFFINITIES[skill].half)} | ${label(SKILL_AFFINITIES[skill].attribute)} |`),
  '',
  'A max key attribute of 6+ raises half to full; 7+ opens a skill at half.',
  '',
  '## Species per skill',
  '',
  '| Skill | Full | Half |',
  '|---|---:|---:|',
  ...skills.map(skill => `| ${label(skill)} | ${profiles.filter(({ profile }) => profile[skill] === 'full').length} | ${profiles.filter(({ profile }) => profile[skill] === 'half').length} |`),
  '',
  '## Crafting skills per species',
  '',
  '| Crafting skills | Species |',
  '|---:|---:|',
  ...[0, 1, 2, 3, 4, 5].map(count => `| ${count} | ${profiles.filter(({ profile }) => craftingCount(profile) === count).length} |`),
  '',
  '## Exceptions',
  '',
  '| Species | Skills | Note |',
  '|---|---|---|',
  ...Object.entries(speciesExceptions).map(([name, entry]) => `| ${name}${entry.line ? ' (whole line)' : ''} | ${Object.entries(entry.skills).map(([skill, level]) => `${label(skill)}: ${level ?? 'none'}`).join(', ')} | ${entry.note ?? ''} |`),
  '',
  '## All species',
  '',
  '| # | Species | Types | Full | Half |',
  '|---:|---|---|---|---|',
  ...profiles.map(({ template, profile }) => {
    const level = (wanted: string) => skills.filter(skill => profile[skill] === wanted).map(label).join(', ');
    return `| ${template.number} | ${template.name}${overrides.has(template.name) ? ' ✎' : ''} | ${types(template.types)} | ${level('full')} | ${level('half')} |`;
  }),
];
writeFileSync(new URL('species.md', target), speciesLines.join('\n') + '\n');
console.log(`Wrote ${recipes.length} recipes and ${profiles.length} species profiles to docs/crafting-review/.`);
