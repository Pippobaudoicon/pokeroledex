/** TYPE_CHART transposed: OFFENSIVE_TYPE_CHART[attacker][defender]. */
const OFFENSIVE_TYPE_CHART = (() => {
  const chart: TypeChart = JSON.parse(JSON.stringify(TYPE_CHART));
  const types = Object.keys(chart) as PokemonType[];
  types.forEach((column) => {
    types.forEach((row) => {
      chart[row][column] = TYPE_CHART[column][row];
    });
  });
  return chart;
})();
