import { PokemonType } from "@/api/schemas";

/** chart[a][b] is the damage multiplier of a type-b attack against a type-a defender. */
type TypeChart = Record<PokemonType, Record<PokemonType, number>>;
type Multiplier = 4 | 2 | 1 | 0.5 | 0.25 | 0;

const typesOf = (row: Record<PokemonType, number>) => Object.keys(row) as PokemonType[];

export const useTypeEffectiveness = () => ({
  getDefensiveImmunes: (type: PokemonType) => {
    const row = TYPE_CHART[type];
    return typesOf(row)
      .filter((other) => row[other] === 0)
      .map((other) => PokemonType[other]);
  },
  getOffensiveImmunes: (type: PokemonType) => {
    const row = OFFENSIVE_TYPE_CHART[type];
    return typesOf(row)
      .filter((other) => row[other] === 0)
      .map((other) => PokemonType[other]);
  },
  getDefensiveWeaknesses: (type: PokemonType) => {
    const row = TYPE_CHART[type];
    return typesOf(row)
      .filter((other) => row[other] === 2)
      .map((other) => PokemonType[other]);
  },
  getOffensiveWeaknesses: (type: PokemonType) => {
    const row = OFFENSIVE_TYPE_CHART[type];
    return typesOf(row)
      .filter((other) => row[other] === 2)
      .map((other) => PokemonType[other]);
  },
  getDefensiveStrengths: (type: PokemonType) => {
    const row = TYPE_CHART[type];
    return typesOf(row)
      .filter((other) => row[other] === 0.5)
      .map((other) => PokemonType[other]);
  },
  getOffensiveStrengths: (type: PokemonType) => {
    const row = OFFENSIVE_TYPE_CHART[type];
    return typesOf(row)
      .filter((other) => row[other] === 0.5)
      .map((other) => PokemonType[other]);
  },
  getFullDefensiveChart: () => TYPE_CHART,
  getFullOffensiveChart: () => OFFENSIVE_TYPE_CHART,
  /** Attacking types grouped by their combined multiplier against a one- or two-type defender. */
  getDefensiveChart: (typeOne: PokemonType, typeTwo?: PokemonType) => {
    const chart: Record<Multiplier, PokemonType[]> = {
      4: [],
      2: [],
      1: [],
      0.5: [],
      0.25: [],
      0: [],
    };
    const rowOne = TYPE_CHART[typeOne];
    const rowTwo = typeTwo != null ? TYPE_CHART[typeTwo] : undefined;
    typesOf(rowOne).forEach((attacker) => {
      const multiplierOne = rowOne[attacker];
      const multiplierTwo = rowTwo?.[attacker];
      const multiplier =
        multiplierTwo === undefined ? multiplierOne : multiplierOne * multiplierTwo;
      if (multiplier === 0) chart[0].push(attacker);
      else if (multiplier === 0.25) chart[0.25].push(attacker);
      else if (multiplier === 0.5) chart[0.5].push(attacker);
      else if (multiplier === 1) chart[1].push(attacker);
      else if (multiplier === 2) chart[2].push(attacker);
      else if (multiplier === 4) chart[4].push(attacker);
    });
    return chart;
  },
});
